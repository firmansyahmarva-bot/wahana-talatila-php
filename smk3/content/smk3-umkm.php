<h2 id="kesalahan-umkm">Dua Kesalahan UMKM yang Paling Sering</h2>
<ol>
  <li><strong>Menunggu wajib.</strong> Menunda semua sampai "nanti kalau sudah 100 orang" — lalu tender datang lebih cepat, atau kecelakaannya yang datang lebih dulu. Level 1 di atas tidak menunggu apa pun.</li>
  <li><strong>Langsung beli dokumen lengkap.</strong> UMKM 40 orang membeli paket 200 dokumen korporat — tidak terbaca, tidak dijalankan, dan uangnya hangus. Sistem kecil yang hidup mengalahkan folder besar yang mati; waspadai pola dari <?= ilink('ciri-konsultan-smk3-abal-abal', 'penyedia abal-abal') ?> yang menyasar persis segmen ini.</li>
