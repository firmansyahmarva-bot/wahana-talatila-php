<p>"Perusahaan kecil seperti kami — apa harus repot dengan SMK3?" Pertanyaan yang jujur, dan jawabannya berlapis: kewajiban formal punya ambang yang jelas, tetapi keselamatan tidak mengenal ukuran perusahaan — dan pasar semakin sering meminta bukti sistem bahkan dari pemasok kecilnya. Artikel ini menjernihkan status kewajiban UMKM, lalu memberi jalur penerapan bertahap yang masuk akal untuk usaha kecil: mulai dari yang melindungi nyawa, tumbuh menuju yang membuka pasar.</p>

<h2 id="status-wajib">Status Kewajiban: Dua Ambang yang Perlu Dicek</h2>
<p>PP 50/2012 mewajibkan SMK3 bagi perusahaan yang <strong>mempekerjakan ≥100 orang</strong> atau <strong>berpotensi bahaya tinggi</strong>. Untuk UMKM, artinya:</p>
<ul>
  <li>Usaha 20–50 orang dengan risiko umum (toko, jasa, konveksi kecil): <strong>belum wajib sertifikasi</strong> — tetapi norma K3 dasar tetap berlaku: UU 1/1970, kewajiban P3K di tempat kerja, listrik yang aman, dan seterusnya;</li>
  <li>Usaha kecil dengan proses berbahaya (bengkel las, pengolahan kimia, penggilingan): ambang kedua bisa menyentuh Anda — dan terlepas dari status hukumnya, risikonya nyata hari ini;</li>
  <li>Usaha yang tumbuh mendekati 100 pekerja: lebih murah membangun kebiasaan sekarang daripada dipaksa sistem lengkap nanti dalam waktu sempit.</li>
</ul>
<p>Detail kerangka kewajibannya ada di <?= ilink('regulasi', 'panduan PP 50/2012') ?>, dan konsekuensi mengabaikannya di <?= ilink('sanksi-tidak-menerapkan-smk3', 'artikel tentang sanksi') ?>.</p>

<h2 id="alasan-bisnis">Alasan Bisnis yang Sering Lebih Menentukan</h2>
<ol>
  <li><strong>Masuk rantai pasok besar.</strong> Pabrikan dan proyek besar menilai K3 pemasoknya — bahkan yang kecil. Satu kuesioner vendor bisa menjadi pintu (atau tembok) ke kontrak terbesar Anda.</li>
  <li><strong>Tender.</strong> Bila target pasar Anda mensyaratkan sertifikat SMK3, ukurannya tidak menolong — persyaratan tetap persyaratan.</li>
  <li><strong>Satu kecelakaan = krisis eksistensial.</strong> Perusahaan besar menyerap biaya kecelakaan; UMKM sering tidak — kehilangan pekerja kunci, tuntutan, atau kebakaran kecil bisa mengakhiri usaha.</li>
</ol>

<h2 id="jalur-bertahap">Jalur Bertahap: Tiga Level yang Realistis</h2>
<h3>Level 1 — Fondasi selamat (mulai minggu ini, biaya minimal)</h3>
<ul class="check-list">
  <li>Tulis daftar bahaya utama per area bersama pekerja senior — versi sederhana dari <?= ilink('cara-menyusun-hiradc', 'HIRADC') ?></li>
  <li>Bereskan yang mematikan lebih dulu: listrik semrawut, bahan mudah terbakar dekat api, mesin tanpa pengaman</li>
  <li>APAR sesuai risiko + semua orang tahu memakainya; kotak P3K terisi</li>
  <li>APD dasar untuk pekerjaan yang membutuhkan — dan aturan memakainya</li>
  <li>Satu halaman aturan keselamatan + briefing singkat rutin</li>
</ul>
