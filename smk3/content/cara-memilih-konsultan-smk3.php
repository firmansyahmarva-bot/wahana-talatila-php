<h2 id="10-pertanyaan-penguji">10 Pertanyaan Uji Integritas Sebelum Menandatangani Perjanjian Kerjasama</h2>
<p>Ajukan 10 pertanyaan kritis ini kepada calon Lead Consultant perusahaan Anda saat presentasi proposal:</p>

<ol>
  <li>Bisakah tunjukkan Surat Penunjukan PJK3 resmi dari Kemnaker RI milik perusahaan Anda?</li>
  <li>Berapa banyak perusahaan di sektor industri kami yang telah Anda dampingi hingga lulus audit Emas?</li>
  <li>Bolehkah kami menghubungi 2 manajer HSE dari klien terdahulu Anda untuk meminta referensi?</li>
  <li>Siapa nama Lead Consultant yang akan diterjunkan langsung di lokasi kami, dan apa kualifikasinya?</li>
  <li>Bagaimana metodologi Anda dalam menyusun HIRADC — apakah ditulis tim Anda sendiri atau bersama supervisor kami?</li>
  <li>Berapa kali frekuensi kunjungan lapangan tatap muka yang dijamin dalam perjanjian kontrak?</li>
  <li>Apakah honorarium Man-Days Lembaga Audit Eksternal Kemnaker sudah termasuk dalam proposal ini?</li>
  <li>Apa tindakan yang akan Anda ambil jika dalam Mock Audit ditemukan SILO peralatan utama mati?</li>
  <li>Bagaimana bentuk komitmen pendampingan Anda jika auditor eksternal memberikan temuan CAR pasca-audit?</li>
  <li>Bagaimana skema pembayaran bertahap (milestone) yang dikaitkan dengan bukti fisik keluaran (*deliverables*)?</li>
</ol>

<h2 id="skema-pembayaran-aman">Skema Pembayaran Berbasis Milestone yang Melindungi Konsumen</h2>
<p>Jangan pernah membayar lunas 100% di awal. Gunakan **Skema 4 Tahap Pembayaran Aman**: </p>

<ul class="check-list">
  <li><strong>Termin 1 (DP 30%):</strong> Dibayarkan saat penandatanganan Kontrak &amp; Penyerahan Laporan Gap Analysis Awal.</li>
  <li><strong>Termin 2 (30%):</strong> Dibayarkan setelah seluruh Dokumentasi (Manual/SOP/IK) selesai disahkan &amp; SK P2K3 diajukan ke Disnaker.</li>
  <li><strong>Termin 3 (30%):</strong> Dibayarkan setelah Pelaksanaan Audit Eksternal dan Berita Acara (BAHA) ditandatangani.</li>
  <li><strong>Termin 4 (Pelunasan 10%):</strong> Dibayarkan setelah Surat Keterangan Lulus (SKL) Resmi terbit dari Lembaga Audit.</li>
</ul>

