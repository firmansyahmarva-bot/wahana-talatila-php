<h2 id="daftar-dokumen-wajib">Daftar Dokumen Wajib per Elemen yang Diminta Auditor Eksternal</h2>

<h3 id="dokumen-komitmen-perencanaan">1. Kelompok Dokumen Komitmen &amp; Perencanaan (Elemen 1 &amp; 2)</h3>
<ul>
  <li><strong>Dokumen Kebijakan K3 Tertulis:</strong> Ditandatangani pimpinan tertinggi, memuat komitmen pencegahan cedera &amp; penyakit akibat kerja, serta kepatuhan hukum.</li>
  <li><strong>SK Pengesahan P2K3 Disnaker:</strong> Surat Keputusan pengesahan komite P2K3 dari Dinas Tenaga Kerja Provinsi setempat yang masih berlaku.</li>
  <li><strong>Register HIRADC / IBPR Lengkap:</strong> Tabel identifikasi bahaya dan penilaian risiko yang mencakup seluruh fasilitas, proses produksi, dan area kerja pendukung.</li>
  <li><strong>Matriks Kepatuhan Hukum K3:</strong> Daftar peraturan perundangan K3 (UU, PP, Permenaker, Perda) yang relevan beserta bukti evaluasi pemenuhannya secara periodik.</li>
  <li><strong>Manual SMK3:</strong> Dokumen induk yang menjelaskan arsitektur penerapan 12 elemen di perusahaan.</li>
</ul>

<h3 id="dokumen-pengendalian-operasional">2. Kelompok Prosedur Operasional Utama (Elemen 5, 6, 9)</h3>
<ul>
  <li><strong>SOP Pengendalian Dokumen &amp; Rekaman:</strong> Tata cara penomoran, pengesahan, distribusi salinan terkendali, dan pemusnahan dokumen usang.</li>
  <li><strong>SOP Identifikasi &amp; Evaluasi Pemasok/Kontraktor:</strong> Kriteria seleksi vendor, pembelian barang berbahaya, serta jaminan K3 dalam Purchase Order.</li>
  <li><strong>SOP Sistem Izin Kerja Aman (Permit to Work):</strong> Mengatur penerbitan izin kerja untuk Hot Work, Confined Space, Working at Height, Excavation, dan Electrical Work.</li>
  <li><strong>SOP Lockout &amp; Tagout (LOTO):</strong> Isolasi energi berbahaya saat perbaikan mesin atau instalasi listrik.</li>
  <li><strong>SOP Pengelolaan Bahan Berbahaya &amp; Beracun (B3):</strong> Penyimpanan, pemberian label, penyediaan MSDS Bahasa Indonesia, dan penanganan tumpahan.</li>
</ul>

<h3 id="dokumen-pemantauan-kompetensi">3. Kelompok Dokumen Pemantauan &amp; Kompetensi Teknis (Elemen 7, 8, 12)</h3>
<ul>
  <li><strong>SOP Pelatihan &amp; Pengembangan Kompetensi K3:</strong> Prosedur Analisis Kebutuhan Pelatihan (TNA) serta penyelenggaraan induksi keselamatan.</li>
  <li><strong>Matriks Kompetensi &amp; Lisensi K3 Personil:</strong> Rekam jejak sertifikasi personil berlisensi Kemnaker RI. Memastikan instalasi dan pemeliharaan kelistrikan diawasi oleh personil bersertifikasi resmi melalui [Pena Consultant Pelatihan Ahli K3 Listrik](https://penaconsultant.com/pelatihan/ahli-k3-listrik) adalah bukti pemenuhan kriteria 12.2.1 yang diperiksa ketat oleh auditor.</li>
  <li><strong>SOP Pengukuran Lingkungan Kerja:</strong> Prosedur dan laporan hasil uji fisika, kimia, biologi, ergonomi, dan psikososial di tempat kerja.</li>
  <li><strong>SOP Pemeriksaan Kesehatan Tenaga Kerja (MCU):</strong> Prosedur MCU awal, berkala, dan khusus yang ditandatangani Dokter Berlisensi Hiperkes.</li>
  <li><strong>SOP Investigasi &amp; Pelaporan Kecelakaan Kerja:</strong> Alur pelaporan nearmiss/insiden, metode RCA, dan pelaporan 2x24 jam ke Disnaker/BPJS.</li>
</ul>

<h3 id="dokumen-evaluasi-audit">4. Kelompok Dokumen Evaluasi &amp; Peninjauan (Elemen 11)</h3>
<ul>
  <li><strong>SOP Audit Internal SMK3:</strong> Tata cara pelaksanaan audit internal tahunan, pembentukan tim auditor internal bersertifikat Kemnaker, dan pembuatan Laporan CAR.</li>
  <li><strong>SOP Tinjauan Manajemen (Management Review):</strong> Prosedur pelaksanaan RTM berkala yang membahas efektivitas SMK3 dan alokasi sumber daya perbaikan.</li>
</ul>

