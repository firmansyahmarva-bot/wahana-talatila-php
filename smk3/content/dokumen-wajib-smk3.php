<h2 id="disiplin-pengendalian-dokumen">Disiplin Pengendalian Dokumen (Document Control) Sesuai Elemen 4</h2>
<p>Kegagalan pada Elemen 4 (Pengendalian Dokumen) sering kali meruntuhkan nilai persentase total audit. Auditor akan mengambil 3 sampel SOP secara acak di lapangan dan membandingkannya dengan Master List Dokumen di bagian Document Control. Agar lolos tanpa cela, terapkan aturan wajib berikut:</p>
<ul>
  <li><strong>Header Dokumen Standar:</strong> Setiap halaman dokumen wajib memuat Logo Perusahaan, Judul Dokumen, Nomor Dokumen, Nomor Revisi, Tanggal Efektif, dan Halaman (misal: Halaman 2 dari 5).</li>
  <li><strong>Blok Pengesahan (Approval Matrix):</strong> Dokumen Level 1 dan 2 wajib ditandatangani oleh Pembuat (Author/HSE Manager), Pemeriksa (Reviewer/Operational Director), dan Pengesah (Approver/President Director).</li>
  <li><strong>Cap Salinan Terkendali (Controlled Copy):</strong> Dokumen cetak yang dibagikan ke unit kerja wajib dibubuhi stempel basah berwarna merah "SALINAN TERKENDALI NO: XX". Dokumen tanpa stempel dianggap salinan tak terkendali yang dilarang berada di area kerja.</li>
  <li><strong>Pemusnahan Salinan Usang (Obsolete Document):</strong> Begitu Revisi 02 terbit, seluruh salinan cetak Revisi 01 di lapangan wajib ditarik dan dihancurkan, atau dibubuhi stempel "KEDALUWARSA / OBSOLETE" jika disimpan sebagai arsip sejarah.</li>
</ul>

<h2 id="kesalahan-dokumentasi">5 Jebakan Dokumentasi yang Paling Sering Memicu Temuan Mayor</h2>
<ol>
  <li><strong>SOP Berlawanan dengan Kondisi Fisik Lapangan:</strong> Prosedur menyatakan "Seluruh area produksi dilengkapi Sistem Sprinkler Otomatis", namun di lapangan pabrik hanya menggunakan APAR powder manual.</li>
  <li><strong>Dokumen Hanya Disimpan di Komputer HSE Manager:</strong> Pekerja di lapangan (supervisor/operator) tidak memiliki akses terhadap Prosedur dan Instruksi Kerja yang relevan dengan tugas mereka.</li>
  <li><strong>Penggunaan Template Gratisan Tanpa Editan Spesifik:</strong> Memakai template SOP dari internet yang masih mencantumkan nama PT lain atau menyebut jenis bahaya yang tidak pernah ada di fasilitas perusahaan Anda.</li>
  <li><strong>Struktur P2K3 dalam SOP Berbeda dengan SK Disnaker:</strong> Prosedur P2K3 mencantumkan 8 anggota, sementara SK Resmi Disnaker memuat 12 anggota karena terjadi pergantian struktur yang tidak direvisi dalam dokumen.</li>
  <li><strong>Tidak Adanya Indeks Matriks Penelusuran Bukti (Audit Traceability Index):</strong> Tim HSE panik dan membutuhkan waktu lebih dari 15 menit untuk menemukan 1 lembar laporan kalibrasi alat saat diminta auditor.</li>
</ol>

