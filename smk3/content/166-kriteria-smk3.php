<h2 id="bedah-12-elemen">Bedah Teknis 12 Elemen SMK3 dan Titik Kritis Penilaian Auditor</h2>

<h3 id="elemen-1">Elemen 1: Pembangunan dan Terjaminnya Pelaksanaan Komitmen (26 Kriteria)</h3>
<p>Elemen ini adalah batu penjuru seluruh audit SMK3. Auditor memeriksa apakah manajemen puncak memimpin sistem atau sekadar melimpahkannya ke departemen HSE.</p>
<ul>
  <li><strong>Kriteria 1.1.1 s.d 1.1.5 (Kebijakan K3):</strong> Kebijakan harus tertulis, tertanggal, ditandatangani oleh pimpinan tertinggi di lokasi (Direktur/GM), memuat komitmen perbaikan berkelanjutan, disosialisasikan ke seluruh pekerja, dan ditinjau secara berkala. <br><em>Red Flag Auditor:</em> Kebijakan K3 ditandatangani oleh HR Manager atau Corporate HSE Director di Head Office tanpa ada tanda tangan Plant Manager lokasi lokal yang diaudit.</li>
  <li><strong>Kriteria 1.2.1 s.d 1.2.7 (Tanggung Jawab &amp; Pengesahan P2K3):</strong> Memeriksa SK Pengesahan P2K3 resmi dari Disnaker Provinsi setempat. Sekretaris P2K3 wajib Ahli K3 Umum bersertifikat dan ber-SKP aktif dari Kemnaker RI. <br><em>Point of Failure:</em> Terjadi pergantian Sekretaris P2K3 atau Direktur (Ketua P2K3) tetapi SK P2K3 tidak diperbarui ke Disnaker selama lebih dari 6 bulan.</li>
  <li><strong>Kriteria 1.4.1 s.d 1.4.9 (Tinjauan Manajemen &amp; Pelibatan Karyawan):</strong> Menilai pelaksanaan Rapat P2K3 bulanan dan Rapat Tinjauan Manajemen (RTM) tahunan. Dokumen berupa Notulen, Daftar Hadir, dan Rekam Foto Rapat. Untuk memperkuat bukti pelibatan pekerja dalam sosialisasi keselamatan harian sebelum shift, pelaksanaan dan dokumentasi <?= ilink('k3-pendukung', 'toolbox talk') ?> dipadukan dengan [Wahana Totalita Safety Talk Tools](https://wahanatotalita.com/tools/safety-talk) yang menyediakan kerangka pencatatan ringkas dan terukur.</li>
</ul>

<h3 id="elemen-2">Elemen 2: Pembuatan dan Pendokumentasian Rencana K3 (14 Kriteria)</h3>
<p>Menguji bagaimana perusahaan mengidentifikasi risiko sebelum pekerjaan dimulai dan menetapkan sasaran K3 yang terukur.</p>
<ul>
  <li><strong>Kriteria 2.1.1 s.d 2.1.6 (HIRADC / IBPR):</strong> Identifikasi bahaya harus mencakup seluruh aktivitas rutin, non-rutin, kondisi darurat, serta kontraktor dan tamu. <br><em>Pencegahan NC Mayor:</em> HIRADC harus menampung seluruh bahaya fisik, kimia, biologi, ergonomi, dan psikososial sesuai Permenaker No. 5 Tahun 2018. Jika pabrik Anda memiliki laboratorium tetapi HIRADC tidak memuat paparan bahan kimia volatil, kriteria ini gugur.</li>
  <li><strong>Kriteria 2.2.1 s.d 2.3.2 (Peraturan Perundangan &amp; Rencana Kerja):</strong> Adanya Matriks Evaluasi Kepatuhan Hukum K3. Tidak cukup hanya mendaftar nomor undang-undang; perusahaan wajib membuktikan kepatuhan spesifik pasal demi pasal.</li>
</ul>

<h3 id="elemen-3">Elemen 3: Pengendalian Perancangan dan Peninjauan Kontrak (8 Kriteria)</h3>
<p>Sering menjadi area terlemah perusahaan manufaktur dan kontraktor pada audit 166 Kriteria Lanjutan.</p>
<ul>
  <li><strong>Kriteria 3.1.1 s.d 3.1.4 (Perancangan Modifikasi):</strong> Prosedur <em>Management of Change (MOC)</em>. Setiap pembelian mesin baru, perubahan alur proses produksi, atau modifikasi struktur bangunan harus melalui analisis risiko K3 sebelum dieksekusi.</li>
  <li><strong>Kriteria 3.2.1 s.d 3.2.4 (Peninjauan Kontrak):</strong> Memeriksa apakah aspek K3 masuk dalam tinjauan kontrak dengan klien atau subkontraktor.</li>
</ul>

<h3 id="elemen-4">Elemen 4: Pengendalian Dokumen (5 Kriteria)</h3>
<p>Auditor tidak hanya menilai keberadaan dokumen, tetapi juga disiplin versi dan distribusinya.</p>
<ul>
  <li><strong>Kriteria 4.1.1 s.d 4.2.3:</strong> Prosedur pembuatan, perubahan, pengesahan, dan penarikan dokumen usang. <br><em>Temuan Tipikal:</em> Di area produksi terpasang Prosedur Tanggap Darurat Revisi 01, sementara di server master sistem tertulis Revisi 03. Hal ini memicu temuan Minor terkumulasi.</li>
</ul>

<h3 id="elemen-5">Elemen 5: Pembelian dan Pengendalian Barang/Jasa (8 Kriteria)</h3>
<p>Mengunci aspek K3 pada rantai pasok (supply chain) dan vendor.</p>
<ul>
  <li><strong>Kriteria 5.1.1 s.d 5.4.2:</strong> Spesifikasi K3 wajib dicantumkan dalam <em>Purchase Order (PO)</em> untuk pembelian APD, bahan kimia B3, dan mesin berat. Vendor bahan kimia wajib melampirkan Lembar Data Keselamatan Bahan (LDKB / MSDS) Bahasa Indonesia.</li>
</ul>

<h3 id="elemen-6">Elemen 6: Keamanan Bekerja Berdasarkan SMK3 (40 Kriteria)</h3>
<p>Elemen dengan porsi kriteria terbanyak. Tempat di mana audit fisik di lapangan (site tour) menentukan nasib sertifikasi.</p>
<ul>
  <li><strong>Kriteria 6.1.1 s.d 6.1.7 (Sistem Izin Kerja):</strong> Evaluasi penerapan <em>Permit to Work (PTW)</em> untuk pekerjaan panas (hot work), ruang terbatas (confined space), kerja di ketinggian, dan penggalian.</li>
  <li><strong>Kriteria 6.5.1 s.d 6.5.10 (APD &amp; Pemeliharaan):</strong> Pengelolaan APD wajib melalui analisis kebutuhan berdasar HIRADC, pendistribusian gratis, uji kesesuaian (fit test), dan inspeksi kelayakan berkala.</li>
  <li><strong>Kriteria 6.8.1 s.d 6.8.4 (Persyaratan Alat Angkat-Angkut):</strong> Memeriksa kelayakan alat berat dan kompetensi personil. Pada area logistik dan gudang, seluruh armada angkut wajib memiliki Surat Keterangan Layak K3 yang diterbitkan instansi ketenagakerjaan. Personil yang mengoperasikannya harus menempuh program sertifikasi resmi seperti [LSP APKONT Pelatihan K3 Operator Forklift](https://www.lsp-apkont.net/pelatihan/k3-operator-forklift) untuk menjamin pemenuhan kriteria K3 operasional di lapangan.</li>
</ul>

<h3 id="elemen-7">Elemen 7: Standar Pemantauan (20 Kriteria)</h3>
<p>Fokus pada pengujian lingkungan kerja, pengujian fisik alat, dan pemeriksaan kesehatan tenaga kerja.</p>
<ul>
  <li><strong>Kriteria 7.1.1 s.d 7.1.7 (Pengukuran Lingkungan Kerja):</strong> Pelaksanaan pengujian berkala faktor fisika (kebisingan, pencahayaan, getaran), kimia, biologi, ergonomi, dan psikososial oleh UPTD K3 atau PJK3 Pengujian Lingkungan Kerja yang terakreditasi Kemnaker (Sesuai Permenaker 5/2018).</li>
  <li><strong>Kriteria 7.4.1 s.d 7.4.5 (Pemeriksaan Kesehatan):</strong> MCU Awal, Berkala (minimal 1 tahun sekali), dan Khusus. <br><em>Catatan Khusus Auditor:</em> Dokter yang memeriksa dan menandatangani hasil laporan MCU wajib bersertifikat Hiperkes (Permenaker 01/1976). Jika laporan ditandatangani dokter umum tanpa sertifikat Hiperkes, kriteria ini tidak diakui auditor.</li>
</ul>

<h3 id="elemen-8">Elemen 8: Pelaporan dan Perbaikan Ketidaksesuaian (9 Kriteria)</h3>
<p>Pelaporan insiden, nearmiss, dan tindak lanjut rekomendasi audit.</p>
<ul>
  <li><strong>Kriteria 8.1.1 s.d 8.3.6:</strong> Prosedur investigasi kecelakaan kerja berbasis <em>Root Cause Analysis (RCA)</em>. Bukti pelaporan wajib kecelakaan kerja 2x24 jam ke Disnaker dan BPJS Ketenagakerjaan lokal.</li>
</ul>

<h3 id="elemen-9">Elemen 9: Pengelolaan Material dan Perpindahannya (5 Kriteria)</h3>
<p>Penyimpanan, penanganan, dan tanggap darurat B3 serta limbah berbahaya.</p>
<ul>
  <li><strong>Kriteria 9.1.1 s.d 9.3.5:</strong> Penyediaan tempat penyimpanan B3 bertanggul penampung (secondary containment), secondary labeling, spill kit, dan eyewash station berfungsi penuh.</li>
</ul>

<h3 id="elemen-10">Elemen 10: Pengumpulan dan Penggunaan Data (5 Kriteria)</h3>
<p>Pencatatan statistik K3 dan perhitungan rasio insiden.</p>
<ul>
  <li><strong>Kriteria 10.1.1 s.d 10.2.2:</strong> Data statistik kecelakaan kerja: <em>Frequency Rate (FR)</em> dan <em>Severity Rate (SR)</em> dipublikasikan dan dilaporkan ke P2K3 secara bulanan.</li>
</ul>

<h3 id="elemen-11">Elemen 11: Pemeriksaan Sistem Manajemen (5 Kriteria)</h3>
<p>Verifikasi mandiri melalui audit internal SMK3 secara berkala.</p>
<ul>
  <li><strong>Kriteria 11.1.1 s.d 11.1.5:</strong> Audit internal wajib dilakukan minimal 1 tahun sekali oleh Auditor Internal SMK3 terlisensi Kemnaker. <br><em>Red Flag:</em> Laporan audit internal dibuat H-3 sebelum audit eksternal tanpa melampirkan daftar periksa (checklist) dan verifikasi bukti perbaikan tindak lanjut (CAR).</li>
</ul>

<h3 id="elemen-12">Elemen 12: Pengembangan Keterampilan dan Kemampuan (14 Kriteria)</h3>
<p>Analisis kebutuhan pelatihan K3 dan lisensi personil spesialis.</p>
<ul>
  <li><strong>Kriteria 12.1.1 s.d 12.4.2:</strong> Matriks Analisis Kebutuhan Pelatihan K3 (TNA), pelaksanaan program induksi K3 pengunjung/pekerja baru, serta pemenuhan lisensi personil K3 (Ahli K3, Petugas P3K, Petugas Kebakaran, Operator Alat Angkat Angkut, Ahli K3 Listrik).</li>
</ul>

