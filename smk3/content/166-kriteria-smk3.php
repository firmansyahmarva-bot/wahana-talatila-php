<h2 id="pola-temuan-mayor-lapangan">5 Pola Temuan Mayor Paling Sering Terjadi di Lapangan</h2>
<ol>
  <li><strong>Peralatan Tanpa Riksa Uji (SILO) / Kedaluwarsa:</strong> Mengoperasikan Bejana Tekan, Tangki Timbun, Genset, Air Receiver Tank, atau Crane tanpa Pengesahan Pemakaian dari Disnaker/Kemnaker.</li>
  <li><strong>Personil Tanpa Lisensi K3 (SIO) Resmi:</strong> Operator alat angkat angkut, teknisi listrik, petugas ruang terbatas, atau juru las yang tidak memiliki SIO aktif penerbitan Kemnaker RI.</li>
  <li><strong>P2K3 Tidak Aktif / Tidak Disahkan:</strong> P2K3 tidak memiliki SK Pengesahan dari Disnaker Provinsi, Sekretaris P2K3 tidak ber-SKP aktif, atau tidak menyampaikan Laporan Triwulanan P2K3 ke Disnaker secara rutin.</li>
  <li><strong>HIRADC Tidak Mencakup Aktivitas Lapangan Secara Utuh:</strong> Memiliki dokumen HIRADC tetapi bahaya nyata di lapangan (seperti pekerjaan panas di dekat tangki solar atau bahan kimia korosif) tidak ada di tabel penilaian risiko.</li>
  <li><strong>Pemeriksaan Kesehatan Berkelanjutan Tidak Dilaksanakan:</strong> Perusahaan tidak memiliki Laporan MCU Berkala pekerja atau dokter pemeriksa tidak bersertifikat Hiperkes.</li>
</ol>

