<div class="note"><strong>Filosofi Audit yang Benar:</strong> Audit Internal adalah tempat terbaik bagi perusahaan untuk **menemukan kesalahan sebanyak mungkin** agar dapat diperbaiki. Audit Eksternal adalah tempat di mana seluruh kesalahan tersebut **sudah terbukti 100% diperbaiki**.</div>

