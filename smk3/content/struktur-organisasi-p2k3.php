<div class="note"><strong>Catatan Regulasi:</strong> Struktur organisasi Panitia Pembina Keselamatan dan Kesehatan Kerja (P2K3) mengacu pada Permenaker No. Per-04/MEN/1987 dan PP No. 50 Tahun 2012 Kriteria 1.4. Untuk pendampingan penyusunan struktur dan pembinaan pengurus P2K3 terpadu, konsultasikan bersama tim spesialis <?= ext_link('wt_smk3', 'Wahana Totalita Konsultan') ?> per 2026.</div>

<p>Dalam sebuah audit eksternal SMK3 di kontraktor tambang di Balikpapan, auditor menolak bagan struktur organisasi P2K3 perusahaan karena mencantumkan nama Manajer HSE sebagai Ketua P2K3 dan Staf GA sebagai Sekretaris P2K3. Auditor mencatat **Temuan Mayor Kriteria 1.4.1** karena melanggar ketentuan hukum mendasar: **Ketua P2K3 WAJIB dijabat oleh Pimpinan Tertinggi Perusahaan (Direktur Utama / General Manager)** dan **Sekretaris P2K3 WAJIB dijabat oleh Ahli K3 Umum yang mengantongi SKP &amp; Lisensi Aktif dari Kemnaker RI**. Banyak perusahaan yang menyusun bagan P2K3 sekadar formalitas tempelan di dinding kantor tanpa memahami implikasi hukum dan pembagian peran operasinya. Artikel ini membedah 3 model struktur P2K3 ideal, matriks pembagian tugas per jabatan, dan tata cara verifikasi keabsahan bagan struktur Disnaker.</p>

<h2 id="3-prinsip-hukum">3 Prinsip Hukum Wajib Penyusunan Bagan P2K3 (Permenaker 04/1987)</h2>
<p>Sebelum menggambar bagan organisasi P2K3, perusahaan wajib mengunci 3 aturan hukum yang tidak bisa ditawar oleh auditor eksternal:</p>

<ol>
  <li><strong>Ketua P2K3 = Pimpinan Tertinggi Tempat Kerja (Top Management):</strong> Ketua P2K3 wajib dijabat oleh Direktur Utama, General Manager, atau Plant Manager yang memiliki wewenang hukum untuk memutus keputusan penganggaran dan perbaikan fisik K3.</li>
  <li><strong>Sekretaris P2K3 = Ahli K3 Umum Bersertifikat Kemnaker:</strong> Sekretaris P2K3 wajib diisi oleh personil yang lulus Pembinaan Ahli K3 Umum dan memegang SKP &amp; Lisensi aktif Kemnaker RI.</li>
  <li><strong>Komposisi Bipartit Seimbang (Manajemen &amp; Pekerja):</strong> Anggota P2K3 terdiri dari unsur perwakilan manajemen (para Manajer/Supervisor) dan unsur perwakilan pekerja (Operator, Petugas P3K, Serikat Pekerja).</li>
</ol>

<h2 id="3-model-struktur">3 Model Struktur Organisasi P2K3 Berdasarkan Skala Usaha</h2>

<h3 id="model-1-kecil">Model 1 — Struktur Ramping untuk Perusahaan Skala Kecil (100–200 Pekerja)</h3>
<p>Model ini mengutamakan kecepatan koordinasi tanpa birokrasi berbelit (6–8 Pengurus):</p>
<ul>
  <li><strong>Ketua P2K3:</strong> Direktur Operasional / Manajer Pabrik</li>
  <li><strong>Sekretaris P2K3:</strong> Ahli K3 Umum Perusahaan</li>
  <li><strong>Anggota Unsur Manajemen:</strong> Supervisor Produksi, Supervisor Maintenance, Supervisor HR/GA</li>
  <li><strong>Anggota Unsur Pekerja:</strong> Perwakilan Operator Shift A, Shift B, dan Petugas P3K</li>
</ul>

