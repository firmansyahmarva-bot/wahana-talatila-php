<h3 id="model-3-multisite">Model 3 — Struktur Berjenjang untuk Perusahaan Holding / Multi-Site</h3>
<p>Perusahaan dengan banyak lokasi operasional menerapkan **Sistem P2K3 Matriks Terintegrasi**:</p>
<ul>
  <li><strong>P2K3 Site / Lokasi Proyek:</strong> Dibentuk di masing-masing site, disahkan oleh Disnaker Provinsi setempat, dan dipimpin oleh Project Manager / Site Manager lokasi.</li>
  <li><strong>Komite K3 Korporat (Head Office):</strong> Bertindak sebagai pengawas konsolidasi yang mensinkronkan standar dokumen, anggaran, dan menyelenggarakan audit internal cross-site.</li>
</ul>

