<h2 id="5-kesalahan-bagan">5 Kesalahan Fatal Penulisan Bagan P2K3 yang Menggugurkan Audit</h2>
<ol>
  <li><strong>Nama Sekretaris Tidak Match dengan Lisensi Kemnaker:</strong> Menuliskan nama staf HSE baru di bagan p2k3 padahal SKP Ahli K3 Umum yang terbit di SK Disnaker masih atas nama karyawan lama yang sudah *resign*.</li>
  <li><strong>Ketua P2K3 Dijabat oleh HSE Coordinator:</strong> Direktur Utama enggan masuk dalam bagan organisasi P2K3, sehingga posisi Ketua diserahkan ke Manajer HSE. Ini adalah Temuan Mayor Kritis.</li>
  <li><strong>Bagan P2K3 Berbeda Antara Dokumen SOP dengan SK Disnaker:</strong> Memperbarui bagan P2K3 di papan pengumuman tanpa mengurus permohonan SK Pengesahan Perubahan P2K3 ke Disnaker Provinsi.</li>
  <li><strong>Tidak Ada Unsur Perwakilan Worker sama sekali:</strong> Seluruh anggota P2K3 diisi oleh jajaran Manajer dan Kepala Seksi tanpa melibatkan operator lapangan.</li>
  <li><strong>Pengurus P2K3 Tidak Tahu Nama Mereka Masuk Bagan:</strong> Saat auditor mewawancarai anggota P2K3 dari bagian Gudang, pekerja tersebut mengaku tidak pernah diajak rapat P2K3 dan tidak tahu namanya tertera di bagan.</li>
</ol>

