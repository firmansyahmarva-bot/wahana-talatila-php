<div class="note"><strong>Catatan Regulasi:</strong> Penerapan K3 sektor konstruksi mengacu pada PP No. 50 Tahun 2012 (Kemnaker) dan Permen PUPR No. 10 Tahun 2021 tentang Pedoman Penerapan Sistem Manajemen Keselamatan Konstruksi (SMKK). Untuk konsultasi dan audit kesiapan K3 konstruksi multi-site, tim ahli <?= ext_link('wt_smk3', 'Wahana Totalita Konsultan') ?> menyediakan pendampingan terpadu per 2026.</div>

<p>Sebuah kontraktor spesialis struktur baja di Jakarta didiskualifikasi dari pembuktian kualifikasi tender proyek pembangunan gedung pemerintah senilai Rp 45 Miliar. Manajemen telah melampirkan berkas penawaran yang sangat bersaing, namun gugur di tahap verifikasi dokumen K3 karena Sertifikat SMK3 Kemnaker milik perusahaan telah kedaluwarsa 2 bulan. Di saat yang sama, tim HSE proyek mereka di lapangan ditegur keras oleh pengawas PUPR karena pekerja sub-kontraktor memanjat perancah (scaffolding) 12 meter tanpa Sabuk Keselamatan (Full Body Harness) dan tanpa adanya Izin Kerja Ketinggian (Working at Height Permit). Sektor konstruksi adalah industri berisiko fatalitas tertinggi di Indonesia. Memahami integrasi SMK3 Kemnaker dan SMKK PUPR bukan sekadar untuk lolos tender, melainkan pertaruhan reputasi legalitas dan keselamatan jiwa di area proyek.</p>

