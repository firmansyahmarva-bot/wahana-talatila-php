<h2 id="6-risiko-fatal-konstruksi">6 Risiko Fatalitas Dominan Proyek Konstruksi &amp; Pengendalian Kritis Auditor</h2>

<h3 id="1-bekerja-ketinggian">1. Jatuh dari Ketinggian (Working at Height)</h3>
<p>Penyumbang 50%+ angka fatalitas di proyek konstruksi. Auditor memeriksa ketat:</p>
<ul>
  <li><strong>Kelayakan Perancah (Scaffolding):</strong> Inspeksi fisik pipa, clamp, baseplate, serta pemasangan **Tagging Scaffolding** (Tag Hijau = Aman, Tag Merah = Dilarang Pakai) oleh Scaffolder Bersertifikat Kemnaker.</li>
  <li><strong>Sistem Proteksi Jatuh:</strong> Pemasangan *Safety Net* (jaring pengaman), *Lifeline* kawat baja 8mm, dan pengunaan Full Body Harness *Double Lanyard Absorber*. Untuk sertifikasi personil teknis di Jawa Timur dan sekitarnya, layanan pembinaan keselamatan dapat dikonsultasikan melalui unit teknis <?= ext_link('wt_ketinggian', 'K3 Ketinggian Wahana Totalita') ?>.</li>
</ul>

<h3 id="2-alat-berat-lifting">2. Operasi Alat Berat &amp; Pengangkatan (Lifting Operation)</h3>
<p>Penggunaan Tower Crane, Mobile Crane, Excavator, dan Passenger Hoist:</p>
<ul>
  <li><strong>Surat Keterangan Layak K3 (SILO):</strong> Riksa uji resmi alat berat yang terbit dari Disnaker/Kemnaker setempat.</li>
  <li><strong>Lisensi K3 Operator (SIO):</strong> SIO Operator Crane, Rigger (Juru Ikat), dan Signalman yang masih aktif.</li>
  <li><strong>Dokumen Lifting Plan:</strong> Analisis kapasitas angkat (*Load Chart*), kondisi tanah (*Outrigger Matting*), dan barikade radius putar crane untuk angkatan kritikal (&gt;20 Ton atau *critical lift*).</li>
</ul>

<h3 id="3-galian-tanah">3. Penggalian Tanah Dalam (Excavation Safety)</h3>
<p>Bahaya tanah longsor dan terperangkap pada penggalian &gt;1.5 meter:</p>
<ul>
  <li>Pemasangan dinding penahan tanah (*shoring/sloping/benching*).</li>
  <li>Penyediaan tangga akses keluar-masuk setiap jarak 7.5 meter dan pemeriksaan gas beracun jika galian tergolong ruang terbatas.</li>
</ul>

<h3 id="4-listrik-sementara">4. Instalasi Listrik Sementara Proyek (Temporary Electrical Work)</h3>
<p>Kabel terkelupas terendam air hujan atau panel listrik tanpa Earth Leakage Circuit Breaker (ELCB):</p>
<ul>
  <li>Penggunaan Panel Listrik Proyek standar bertipe weatherproof dengan pengaman ELCB sensitivitas 30mA.</li>
  <li>Pemeriksaan berkala oleh Teknisi Listrik berlisensi Kemnaker RI.</li>
</ul>

<h3 id="5-pekerjaan-panas">5. Pekerjaan Panas &amp; Pengelasan Structure (Hot Work)</h3>
<p>Bahaya kebakaran percikan las mengenai material stirofoam, bahan kimia, atau kayu perancah:</p>
<ul>
  <li>Penerbitan Izin Kerja Panas (Hot Work Permit), penyiapan APAR 6kg siap pakai, penyediaan *Fire Blanket*, dan penunjukan petugas *Fire Watch* selama pekerjaan dan 30 menit setelahnya.</li>
</ul>

<h3 id="6-runtuhnya-bekisting">6. Kegagalan Struktur Bekisting &amp; Pengecoran (Formwork Failure)</h3>
<p>Bahaya robohnya struktur saat pembetonan lantai atas:</p>
<ul>
  <li>Perhitungan desain beban bekisting oleh Enjinir Struktur dan verifikasi lembar izin pengecoran (*Pouring Permit*) sebelum beton dituangkan.</li>
</ul>

<h2 id="pengelolaan-subkontraktor">Pengendalian K3 Sub-Kontraktor (Sub-Contractor Safety Management)</h2>
<p>Sebagian besar tenaga kerja di proyek konstruksi berasal dari mandor atau perusahaan sub-kontraktor. Dalam kriteria audit SMK3 Elemen 5 &amp; 9, seluruh tindakan sub-kontraktor sepenuhnya menjadi **tanggung jawab hukum Kontraktor Utama (General Contractor)**. Sistem penguncian wajib meliputi:</p>

