<p>Manajemen sebuah perusahaan pabrik pengemasan makanan di Karawang terkejut ketika tim auditor eksternal dari Lembaga Audit Kemnaker membatalkan pengajuan resertifikasi SMK3 mereka di hari pertama audit. Penyebabnya adalah saat auditor meminta bukti Laporan Triwulanan P2K3 dan Notulen Rapat Bulanan K3 selama 3 tahun terakhir, tim perusahaan hanya bisa menyerahkan berkas 2 bulan terakhir sebelum audit, sementara berkas 34 bulan sebelumnya kosong tanpa aktivitas. Auditor menegaskan bahwa **Sertifikasi SMK3 bukanlah penilaian sesaat (*snapshot*), melainkan penilaian konsistensi penerapan selama 36 bulan**. Memahami prosedur perpanjangan sertifikat (resertifikasi) secara tepat adalah kunci mempertahankan Bendera Emas dan menghindari kegagalan audit. Artikel ini membedah alur resertifikasi, strategi naik kualifikasi ke 166 kriteria, dan cara memulihkan sistem yang sempat mati suri secara sah.</p>

