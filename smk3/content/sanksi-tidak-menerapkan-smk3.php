<h2 id="lapis-2-pertanggungjawaban-pidana">Lapis 2 — Pertanggungjawaban Pidana Pengurus Saat Insiden Fatal (Fatality)</h2>
<p>Inilah aspek hukum yang paling ditakuti oleh jajaran Direksi dan Manajer Operasional. Apabila terjadi kecelakaan kerja fatal (*fatality*) yang mengakibatkan pekerja cacat permanen atau meninggal dunia, tim Satreskrim Kepolisian RI bersama Pengawas Ketenagakerjaan akan melakukan investigasi olah TKP (OlTKP).</p>

<p>Jika dalam investigasi terbukti bahwa kecelakaan disebabkan oleh **kelalaian pemenuhan norma K3** (seperti APD tidak disediakan, instruksi kerja LOTO tidak dibuat, atau alat tidak di-Riksa Uji), pengurus perusahaan dapat dijerat pasal pidana:</p>

<ul>
  <li><strong>Pasal 15 Ayat (2) UU No. 1 Tahun 1970 tentang Keselamatan Kerja:</strong> Ancaman pidana kurungan selama-lamanya 3 (tiga) bulan atau denda bagi pengurus yang melanggar norma keselamatan kerja.</li>
  <li><strong>Pasal 359 Kitab Undang-Undang Hukum Pidana (KUHP):</strong> <em>"Barangsiapa karena kesalahannya (kealpaannya) menyebabkan orang lain mati, diancam dengan pidana penjara paling lama lima tahun."</em></li>
</ul>

<div class="note"><strong>Pembeda Posisi Hukum:</strong> Jika perusahaan memiliki Sistem SMK3 yang HIDUP (terbukti dari Register HIRADC, Bukti Pelatihan, dan Form Izin Kerja Aman/PTW), manajemen dapat membuktikan bahwa perusahaan telah melakukan **Upaya Pencegahan Maksimalkan (Due Diligence)**. Sebaliknya, jika SMK3 fiktif atau tidak ada, posisi hukum direksi sangat lemah di hadapan penyidik.</div>

<h2 id="lapis-3-kerugian-bisnis">Lapis 3 — Kerugian Bisnis Sistemis yang Terasa Lebih Cepat</h2>
<p>Sebelum Pengawas Ketenagakerjaan datang menerbitkan Nota Pemeriksaan, pengabaian SMK3 sudah memicu kerugian finansial yang merusak bisnis:</p>

<ol>
  <li><strong>Gugur Otomatis dalam Prakualifikasi Tender BUMN &amp; LPSE:</strong> Panitia tender proyek konstruksi dan BUMN kini menetapkan Sertifikat SMK3 PP 50/2012 sebagai syarat gugur administrasi.</li>
  <li><strong>Terdepak dari Daftar Vendor Resmi (CSMS Approval):</strong> Perusahaan migas dan manufaktur multinasional tidak akan meloloskan penilaian CSMS vendor yang tidak memiliki bukti sistem K3 berjalan.</li>
  <li><strong>Lonjakan Biaya Klaim BPJS Ketenagakerjaan &amp; Asuransi:</strong> Tingginya angka kecelakaan kerja meningkatkan rasio klaim yang berdampak pada pengenaan denda insentif BPJS TK.</li>
  <li><strong>Biaya Tersembunyi Kecelakaan Kerja (Iceberg Costs):</strong> Biaya kerugian fisik mesin yang rusak, investigasi internal, dan rusaknya reputasi nama baik perusahaan mencapai 5 hingga 50 kali lipat dari biaya pengobatan medis pekerja.</li>
</ol>

