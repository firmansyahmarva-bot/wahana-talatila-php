<h2 id="dasar-hukum-kewajiban">Dasar Hukum Kewajiban Penerapan SMK3</h2>
<p>Kewajiban penerapan SMK3 diatur secara tegas dalam undang-undang ketenagakerjaan Indonesia:</p>

<ul>
  <li><strong>Pasal 87 Ayat (1) UU No. 13 Tahun 2003 tentang Ketenagakerjaan:</strong> <em>"Setiap perusahaan wajib menerapkan sistem manajemen keselamatan dan kesehatan kerja yang terintegrasi dengan sistem manajemen perusahaan."</em></li>
  <li><strong>Pasal 5 PP No. 50 Tahun 2012:</strong> Mempertegas bahwa kewajiban tersebut berlaku bagi perusahaan yang:
    <ol>
      <li>Mempekerjakan tenaga kerja sekurang-kurangnya **100 (seratus) orang**; ATAU</li>
      <li>Mempunyai tingkat **potensi bahaya tinggi** (seperti industri kimia B3, eksplorasi migas, pertambangan, konstruksi, dan peledakan).</li>
    </ol>
  </li>
</ul>

