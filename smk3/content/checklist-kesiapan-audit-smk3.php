<div class="note"><strong>Catatan Regulasi:</strong> Instrumen checklist kesiapan audit SMK3 mengacu pada Lampiran II PP No. 50 Tahun 2012 dan Permenaker No. 26 Tahun 2014. Untuk audit kesiapan pra-sertifikasi independen, hubungi tim spesialis <?= ext_link('wt_smk3', 'Wahana Totalita Konsultan') ?> per 2026.</div>

<p>Dalam verifikasi H-7 sebelum kedatangan auditor eksternal Kemnaker di sebuah fasilitas gudang logistik di Bekasi, tim HSE menemukan bahwa 4 unit APAR di area loading dock belum diisi ulang dan SK P2K3 Disnaker belum diperbarui setelah sekretaris lama *resign*. Karena keterlambatan penemuan celah ini, perusahaan harus menunda jadwal audit eksternal yang sudah di-booking 1 bulan sebelumnya, yang berakibat pada pembatalan keikutsertaan tender. Menemukan kekurangan K3 saat auditor eksternal sudah berada di meja rapat adalah kesalahan yang sangat mahal. Checklist Kesiapan Audit SMK3 ini dirancang sebagai instrumen verifikasi mandiri (*Self-Assessment Instrument*) yang mencakup 5 area krusial pemeriksaan auditor Kemnaker RI.</p>

<h2 id="petunjuk-penggunaan">Petunjuk Penggunaan Checklist &amp; Bobot Penilaian</h2>
<p>Beri tanda centang pada setiap butir checklist: <strong>TERPENUHI (Score 1)</strong>, <strong>SEBAGIAN (Score 0.5)</strong>, atau <strong>BELUM (Score 0)</strong>. Seluruh butir yang ditandai simbol bintang merah (★) adalah **Syarat Kritis Mutlak**. Apabila terdapat 1 saja butir (★) bertanda BELUM, perusahaan dilarang keras mengajukan audit eksternal.</p>

<h2 id="area-1-dokumen">Area 1 — Kelengkapan Dokumentasi Sistem (PP 50/2012 Elemen 1, 2, 3)</h2>
<ul class="check-list">
  <li>★ Kebijakan K3 tertulis, ditandatangani pimpinan tertinggi, bertanggal, dan dipajang di seluruh area.</li>
  <li>★ Register HIRADC lengkap mencakup seluruh proses rutin &amp; non-rutin, serta ditinjau dalam 12 bulan terakhir.</li>
  <li>★ Manual SMK3 dan Prosedur Wajib (Pengendalian Dokumen, LOTO, PTW, Tanggap Darurat) terkendali.</li>
  <li>Matriks Kepatuhan Peraturan Perundangan K3 terbaru (Permenaker 5/2018, PP 50/2012, dll) terdokumentasi.</li>
  <li>Sasaran &amp; Program K3 Tahunan ditetapkan, memiliki indikator terukur, dan dipantau bulanan.</li>
  <li>Buku Pedoman K3 Kontraktor &amp; Prosedur Pembelian B3 tersedia dan dijalankan.</li>
</ul>

<h2 id="area-2-organisasi">Area 2 — Legalitas Organisasi &amp; Kualifikasi Personil (Elemen 1.4 &amp; 12)</h2>
<ul class="check-list">
  <li>★ Surat Keputusan Pengesahan P2K3 dari Disnaker Provinsi masih berlaku aktif.</li>
  <li>★ Sekretaris P2K3 memiliki SKP Ahli K3 Umum &amp; Kartu Tanda Kewenangan (Lisensi) aktif Kemnaker.</li>
  <li>Petugas Khusus K3 (Petugas P3K, Petugas Kebakaran, Operator Forklift/Crane) memiliki SIO Kemnaker aktif.</li>
  <li>Bukti Laporan Triwulanan P2K3 ke Disnaker Provinsi lengkap 4 triwulan terakhir.</li>
  <li>Matriks Pelatihan K3 Karyawan (Safety Awareness, Induksi K3, Emergency Response) terarsip rapi.</li>
  <li>Tim pendamping manajemen siap menghadapi wawancara auditor Kemnaker RI.</li>
</ul>

<h2 id="area-3-kondisi-fisik">Area 3 — Kesiapan Fisik &amp; Sarana Keselamatan Lapangan (Elemen 6 &amp; 9)</h2>
<ul class="check-list">
  <li>★ APAR terpasang di tempatnya, terinspeksi bulanan, tekanan gauge hijau, dan akses tidak terhalang.</li>
  <li>★ Pelindung Pengaman Mesin (*Machine Guarding*) terpasang lengkap pada seluruh mesin berputar/pres.</li>
  <li>★ Sistem Tanggul Penampung Tumpahan (*Secondary Containment*) tersedia di gudang penyimpanan B3.</li>
  <li>Sertifikat Layak K3 (SILO) Peralatan Utilitas (Boiler, Bejana Tekan, Crane, Lift, Hydrant) aktif.</li>
  <li>Jalur Evakuasi Darurat, Lampu Emergency, dan Pintu Darurat terbebas dari tumpukan barang.</li>
  <li>Marka Jalur Pejalan Kaki, Rambu K3, dan Label B3 (GHS Hazard Label) terpasang jelas.</li>
  <li>APD Standar tersedia lengkap, terdistribusi ke pekerja, dan dipakai 100% di area operasional.</li>
  <li>Stasiun pencuci mata (*Eyewash/Safety Shower*) berfungsi normal dengan tekanan air memadai.</li>
</ul>

<h2 id="area-4-rekaman">Area 4 — Bukti Rekaman Penerapan Nyata (Elemen 5, 7, 8, 11)</h2>
<ul class="check-list">
  <li>★ Laporan Audit Internal SMK3 &amp; Risalah Rapat Tinjauan Manajemen (RTM) 12 bulan terakhir ada.</li>
  <li>★ Form Izin Kerja Aman (PTW Panas, Ketinggian, Ruang Terbatas) terisi lengkap dengan tanda tangan pengawas.</li>
  <li>Notulen Rapat P2K3 Bulanan lengkap dengan daftar hadir dan tindak lanjut perbaikan.</li>
  <li>Form Checklist Inspeksi K3 Mingguan/Bulanan terisi dan bukti perbaikan fisik terarsip.</li>
  <li>Hasil Pengukuran Lingkungan Kerja (Kebisingan, Debu, Cahaya) dari Laboratorium Terakreditasi ada.</li>
  <li>Laporan Pemeriksaan Kesehatan Berkala (MCU) Karyawan terarsip beserta analisis *Fit to Work*.</li>
  <li>Laporan Simulasi Tanggap Darurat (*Emergency Drill*) dilaksanakan minimal 1x dalam 12 bulan.</li>
</ul>

<h2 id="area-5-administrasi">Area 5 — Administrasi &amp; Fasilitas Audit Hari-H</h2>
<ul class="check-list">
  <li>Ruang Rapat Audit, Proyektor LCD, dan Akses Dokumen Master disiapkan untuk Tim Auditor.</li>
  <li>Daftar Pendamping Internal (*Escort Team*) per area/departemen ditetapkan dan dibriefing.</li>
  <li>Dokumen Legalitas Perusahaan (NIB, SIUP, Wajib Lapor Ketenagakerjaan) siap ditunjukkan.</li>
</ul>

