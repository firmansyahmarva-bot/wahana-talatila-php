<h2 id="5-langkah-menjalankan-pelatihan">5 Langkah Efektif Menjalankan Program Training K3 di Perusahaan</h2>
<ol class="steps">
  <li><strong>Langkah 1 — Susun Matriks Kebutuhan Pelatihan (TNA):</strong> Petakan lisensi apa yang wajib dimiliki personil berdasarkan HIRADC (misal: Pabrik memiliki 4 Crane = Wajib 4 Operator SIO Crane).</li>
  <li><strong>Langkah 2 — Buat Kalender Tahunan Program Pelatihan K3:</strong> Tetapkan jadwal bulanan pelaksanaan *Induksi K3, Safety Talk Mingguan, dan Refresher Awareness*.</li>
  <li><strong>Langkah 3 — Gunakan Metode Pelatihan Praktis &amp; Visual:</strong> Jangan hanya membacakan slide peraturan. Gunakan foto temuan bahaya riil di pabrik dan simulasikan penggunaan APAR secara langsung.</li>
  <li><strong>Langkah 4 — Lakukan Evaluasi Post-Test Pasca-Pelatihan:</strong> Pastikan peserta mencapai nilai kelulusan minimal (misal: Skor 75). Jika tidak lulus, berikan sesi pengulangan (*remedial*).</li>
  <li><strong>Langkah 5 — Arsipkan Berkas Pelatihan ke dalam Binder Elemen 3:</strong> Simpan seluruh bukti foto, presensi, dan sertifikat ke dalam folder kearsipan yang siap ditunjukkan saat audit eksternal.</li>
</ol>

