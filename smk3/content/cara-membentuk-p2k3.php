<h2 id="6-langkah-pengesahan">6 Langkah Pembentukan hingga Terbit SK Pengesahan Disnaker</h2>

<h3 id="langkah-1-persiapan-ak3u">Langkah 1: Memastikan Ketersediaan Ahli K3 Umum Aktif</h3>
<p>Kunci utama pengajuan P2K3 adalah dokumen Sekretaris P2K3. Pastikan staf yang ditunjuk telah lulus Pelatihan Ahli K3 Umum Kemnaker RI dan memiliki salinan Sertifikat + Kartu Lisensi (SIO) + Surat Keputusan Penunjukan (SKP) dari Kemnaker yang masih berlaku.</p>

<h3 id="langkah-2-pemilihan-anggota">Langkah 2: Musyawarah Pemilihan Anggota Bipartit</h3>
<p>Mengadakan rapat internal bersama perwakilan divisi dan serikat pekerja untuk memilih perwakilan anggota P2K3. Dokumentasikan musyawarah ini dalam risalah rapat pembentukan P2K3.</p>

<h3 id="langkah-3-sk-internal">Langkah 3: Penerbitan SK Internal Pembentukan P2K3</h3>
<p>Direktur Utama menerbitkan Surat Keputusan Internal Perusahaan tentang Pembentukan P2K3 yang melampirkan susunan nama, jabatan perusahaan, dan posisi dalam komite P2K3.</p>

<h3 id="langkah-4-berkas-permohonan">Langkah 4: Penyusunan Berkas Permohonan Pengesahan</h3>
<p>Menyiapkan berkas fisik/digital surat permohonan pengesahan yang ditujukan kepada Kepala Dinas Tenaga Kerja Provinsi setempat dengan lampiran wajib:</p>
<ul>
  <li>Surat Permohonan Resmi bertandatangan Direktur di atas kop surat perusahaan.</li>
  <li>SK Internal Pembentukan P2K3 bertandatangan Direktur.</li>
  <li>Daftar Struktur &amp; Nama Anggota P2K3.</li>
  <li>Fotokopi Sertifikat Pembinaan Ahli K3 Umum Sekretaris P2K3.</li>
  <li>Fotokopi SKP (Surat Keputusan Penunjukan) Ahli K3 Sekretaris P2K3 dari Kemnaker RI.</li>
  <li>Fotokopi Kartu Lisensi / SIO Ahli K3 Umum yang masih berlaku.</li>
  <li>Bukti Wajib Lapor Ketenagakerjaan (WLKP) perusahaan yang masih aktif.</li>
  <li>Profil Ringkas Tempat Kerja &amp; Jumlah Tenaga Kerja.</li>
</ul>

<h3 id="langkah-5-submission">Langkah 5: Penyerahan Berkas &amp; Verifikasi Disnaker</h3>
<p>Menyerahkan berkas permohonan ke Seksi Pengawasan Ketenagakerjaan Disnaker Provinsi setempat (secara fisik atau melalui portal perizinan online Disnaker). Tim Pengawas Ketenagakerjaan akan memverifikasi keabsahan dokumen SKP Ahli K3 Sekretaris.</p>

<h3 id="langkah-6-terbit-sk">Langkah 6: Penerbitan &amp; Pengarsipan SK Pengesahan P2K3</h3>
<p>Setelah diverifikasi, Kepala Dinas Tenaga Kerja Provinsi menerbitkan **Surat Keputusan Pengesahan P2K3** yang dibubuhi stempel resmi instansi. Dokumen ini wajib diarsipkan dalam *Binder Legalitas K3* dan dipajang salinannya di papan pengumuman perusahaan.</p>

<h2 id="kewajiban-pelaporan-triwulanan">Kewajiban Pelaporan Triwulanan P2K3 (Quarterly Reporting)</h2>
