<div class="note"><strong>Catatan Regulasi:</strong> Pembentukan, susunan, dan tata kerja P2K3 mengacu pada UU No. 1 Tahun 1970 Pasal 10 dan Permenaker No. 04 Tahun 1987. Untuk pengajuan pengesahan per 2026, sebagian Disnaker Provinsi telah menggunakan sistem pelayanan perizinan online (SiNaker/JDIH lokal). Selalu konfirmasi petunjuk teknis di Disnakertrans Provinsi tempat fasilitas beroperasi.</div>

<p>Sebuah perusahaan logistik di kawasan Marunda Jakarta Utara mendapati permohonan tender fasilitas gudangnya didiskualifikasi oleh tim procurement BUMN. Penyebabnya adalah dokumen SK P2K3 (Panitia Pembina Keselamatan dan Kesehatan Kerja) yang dilampirkan perusahaan masih dalam bentuk "Surat Keputusan Internal Direksi" tanpa ada Stempel Pengesahan Resmi dari Dinas Tenaga Kerja Provinsi. Lebih dari itu, posisi Sekretaris P2K3 diisi oleh staf Admin HRD yang belum memiliki Sertifikat Ahli K3 Umum Kemnaker. Kasus ini membuktikan bahwa P2K3 bukan sekadar komite internal organisasi, melainkan lembaga bipartit resmi yang memiliki kekuatan legal hukum ketenagakerjaan dan menjadi syarat mutlak kualifikasi audit SMK3 Kriteria 1.2.2.</p>

<h2 id="dasar-hukum-kewajiban">Dasar Hukum dan Ambang Batas Wajib Pembentukan P2K3</h2>
<p>Kewajiban pembentukan Panitia Pembina Keselamatan dan Kesehatan Kerja (P2K3) diatur secara eksplisit dalam 2 regulasi utama:</p>
<ul>
  <li><strong>UU No. 1 Tahun 1970 Pasal 10:</strong> Menteri Ketenagakerjaan berwenang mewajibkan pengusaha membentuk P2K3 guna memperkembangkan kerja sama, saling pengertian, dan partisipasi efektif dalam penerapan K3.</li>
  <li><strong>Permenaker No. 04 Tahun 1987:</strong> Mengatur juknis pembentukan, susunan keanggotaan, serta kewajiban pelaporan triwulanan ke dinas setempat.</li>
</ul>

<h3 id="dua-ambang-batas">Dua Ambang Batas Wajib Pembentukan P2K3 (Pasal 2 Permenaker 04/1987)</h3>
<p>Setiap tempat kerja wajib membentuk P2K3 apabila memenuhi salah satu kriteria berikut:</p>
<ol>
  <li>Mempekerjakan <strong>100 orang tenaga kerja atau lebih</strong> (kumulatif organik, kontrak, dan alih daya).</li>
  <li>Mempekerjakan <strong>kurang dari 100 orang</strong>, tetapi tempat kerja menggunakan bahan, proses, atau instalasi yang mempunyai potensi bahaya besar (peledakan, kebakaran, keracunan, radiasi, atau penggunaan kimia B3).</li>
</ol>

