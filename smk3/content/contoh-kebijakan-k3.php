<h2 id="proses-penetapan-legalitas">Alur 4 Tahap Penetapan Kebijakan K3 yang Sah (Legal Approval Workflow)</h2>
<p>Kebijakan K3 tidak boleh disusun secara sepihak di balik meja HSE Manager. Agar diakui auditor Kemnaker, ikuti alur 4 tahap resmi berikut:</p>

<ol class="steps">
  <li><strong>Tahap 1 — Konsultasi Wakil Pekerja (Worker Consultation):</strong> Draf Kebijakan K3 dibahas dalam Rapat P2K3 bersama wakil serikat pekerja / perwakilan divisi operasional. Buat risalah rapat dan daftar hadir sebagai bukti kriteria 1.1.2.</li>
  <li><strong>Tahap 2 — Penandatanganan Eksekutif (Executive Signing):</strong> Draf final dicetak di atas kop surat resmi perusahaan dan ditandatangani secara basah (atau digital bersertifikat) oleh pimpinan tertinggi di lokasi setempat.</li>
  <li><strong>Tahap 3 — Penomoran Pengendalian Dokumen (Document Control Tagging):</strong> Bagian Document Control memberikan nomor dokumen resmi (misal: `MAN-SOP-HSE-001`), nomor revisi, dan memasukkannya ke dalam Master List Pengendalian Dokumen.</li>
  <li><strong>Tahap 4 — Sosialisasi &amp; Distrbusi Salinan Terkendali:</strong> Dipajang di lokasi strategis (Lobby, Gate Masuk, Area Produksi, Canteen) dan dibagikan ke unit kerja dengan stempel "SALINAN TERKENDALI".</li>
</ol>

<h2 id="5-pola-temuan-audit">5 Pola Temuan Auditor yang Sering Menggugurkan Kebijakan K3</h2>
<ol>
  <li><strong>Pimpinan Tertinggi Berganti, Tanda Tangan Kebijakan Tidak Diperbarui:</strong> Tanda tangan masih menggunakan pejabat lama yang sudah tidak aktif di perusahaan.</li>
  <li><strong>Teks Kebijakan Sangat Generik Tanpa Menyebut Sektor Bisnis:</strong> Memakai draf internet tanpa menyebutkan apakah perusahaan bergerak di industri kimia, tekstil, atau konstruksi.</li>
  <li><strong>Kebijakan Dinding Berbeda dengan Kebijakan File Master:</strong> Di dinding pabrik terpasang Kebijakan Tahun 2022 (Revisi 01), sementara di server HSE tercantum Kebijakan Tahun 2024 (Revisi 02).</li>
  <li><strong>Pekerja Lapangan Tidak Pernah Melihat atau Mendengar Isinya:</strong> Saat auditor mewawancarai operator di stasiun kerja, pekerja tidak tahu tempat pemasangan Kebijakan K3.</li>
  <li><strong>Tidak Adanya Bukti Konsultasi dengan Pekerja:</strong> Tidak ada notulen rapat P2K3 yang membuktikan bahwa draf kebijakan pernah didiskusikan bersama perwakilan karyawan.</li>
</ol>

