<h2 id="dua-pintu-kewajiban">Dua Pintu Kewajiban Mandatori Penerapan SMK3 (Pasal 5 PP 50/2012)</h2>
<p>Pasal 5 Peraturan Pemerintah No. 50 Tahun 2012 menegaskan bahwa kewajiban menerapkan SMK3 berlaku bagi perusahaan yang memenuhi salah satu atau kedua kriteria berikut:</p>

<h3 id="pintu-1">1. Perusahaan yang Mempekerjakan Minimal 100 Orang Tenaga Kerja</h3>
<p>Perhitungan 100 pekerja dihitung secara kumulatif di lokasi fasilitas/tempat kerja, memuat:</p>
<ul>
  <li>Pekerja Tetap (PKWTT) dan Pekerja Kontrak (PKWT).</li>
  <li>Pekerja Alih Daya (Outsourcing) yang bekerja di bawah kendali operasional perusahaan.</li>
  <li>Tenaga kerja harian lepas dan magang (internship).</li>
</ul>

<h3 id="pintu-2">2. Perusahaan dengan Tingkat Potensi Bahaya Tinggi</h3>
<p>Jika jumlah pekerja Anda di bawah 100 orang (misalnya hanya 25 orang), perusahaan **tetap wajib SMK3** apabila proses kerjanya mengandung potensi bahaya tinggi yang dipicu oleh:</p>
<ul>
  <li><strong>Bahan Kimia Bahaya Tinggi:</strong> Pabrik cat, pengolahan bahan peledak, penyimpanan gas bertekanan, atau penggunaan bahan beracun/korosif.</li>
  <li><strong>Sumber Bahaya Fisik &amp; Mesin Berat:</strong> Pengoperasian Boiler (Bejana Uap), Crane/Furnace berkapasitas besar, atau instalasi listrik tegangan tinggi.</li>
  <li><strong>Karasteristik Pekerjaan Berisiko Tinggi:</strong> Pekerjaan di ruang terbatas (confined space), penggalian tanah dalam, atau pekerjaan di ketinggian. Perusahaan yang menugaskan teknisi di ketinggian wajib memastikan bahwa personilnya telah memiliki kualifikasi teknis bersertifikat Kemnaker seperti [Wahana Totalita Pelatihan TKBT II Surabaya](https://wahanatotalita.com/pelatihan/tkbt-ii-surabaya/) guna memenuhi norma K3 teknis sesuai Permenaker 09/2016.</li>
</ul>

