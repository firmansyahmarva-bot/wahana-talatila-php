          Statutory compliance is actively policed by <strong>Labor Inspectors (Pengawas Ketenagakerjaan)</strong> from provincial Manpower offices (<em>Disnaker</em>) and Kemnaker headquarters. With the introduction of updated inspection frameworks (Permenaker 11/2026), labor inspectors have heightened oversight:
        </p>
        <ul style="padding-left: 20px; line-height: 1.8; color: #374151;">
          <li><strong>Unannounced Site Audits:</strong> Authorized entry into any factory, smelter, mine, or construction zone without prior notice.</li>
          <li><strong>Sealing of Machinery:</strong> Immediate mechanical sealing (<em>pembekuan / penyegelan</em>) of unlicensed forklifts, overhead cranes, or pressure vessels lacking current SIA inspection certificates.</li>
          <li><strong>Stop-Work Notices (Nota Pengawasan):</strong> Issuance of binding legal corrective notices. Failure to remediate within statutory timeframes leads to prosecution under Indonesian civil and labor courts.</li>
          <li><strong>Accident Seizure:</strong> In fatal incidents, labor inspectors coordinate with Indonesian National Police (POLRI) forensics, freezing project sites during investigation.</li>
        </ul>
