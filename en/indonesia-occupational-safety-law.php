        <h2 class="en-sec-title">The Legal Basis of Workplace Safety in Indonesia</h2>
        <p class="en-text">
          Occupational Health and Safety in Indonesia—officially termed <em>Keselamatan dan Kesehatan Kerja (K3)</em>—is governed primarily by <strong>Law No. 1 of 1970 (Undang-Undang No. 1 Tahun 1970 tentang Keselamatan Kerja)</strong>. While enacted decades ago, this fundamental law serves as the constitutional backbone for hundreds of subsequent ministerial regulations (<em>Permenaker</em>) and decrees issued by the Ministry of Manpower (Kemnaker).
        </p>
        <p class="en-text">
          Law No. 1/1970 applies universally to any physical workplace within Indonesian jurisdiction where power tools, machinery, pressurized vessels, combustible materials, or elevated work environments exist. It explicitly places the ultimate legal liability on the <strong>Workplace Manager / Plant Director (Pengurus Tempat Kerja)</strong>.
        </p>

        <div class="en-alert-box">
