<h2 id="risiko">Faktor Risiko Ergonomi</h2>
<ul>
  <li><strong>Postur janggal</strong>: membungkuk, memutar badan, menjangkau di atas bahu, jongkok lama.</li>
  <li><strong>Beban manual (manual handling)</strong>: mengangkat, mendorong, menarik, membawa beban berat atau sering.</li>
  <li><strong>Gerakan berulang</strong> dengan siklus pendek — perakitan, pengetikan, pengemasan.</li>
  <li><strong>Tekanan statis</strong>: berdiri/duduk lama tanpa variasi, memegang alat bergetar.</li>
  <li><strong>Desain stasiun kerja buruk</strong>: ketinggian meja salah, layar tidak sejajar mata, pencahayaan kurang.</li>
