<h2 id="induksi">Induksi K3 (Safety Induction)</h2>
<p>Induksi diberikan kepada pekerja baru, pekerja pindahan, kontraktor, dan tamu sebelum memasuki area kerja. Materi minimumnya:</p>
<ul>
  <li>Kondisi dan bahaya yang ada di tempat kerja beserta pengendaliannya.</li>
  <li>Alat pengaman dan <?= ilink('alat-pelindung-diri', 'APD') ?> yang wajib dipakai beserta cara pakainya.</li>
  <li>Prosedur darurat: jalur evakuasi, titik kumpul, alarm, dan lokasi <?= ilink('permenaker-15-2008-p3k', 'fasilitas P3K') ?>.</li>
  <li>Cara melaporkan bahaya, nyaris-celaka, dan kecelakaan.</li>
</ul>

<h2 id="jenis-pelatihan">Jenis Pelatihan K3</h2>
<p>Setelah induksi, pembinaan berlanjut berjenjang sesuai risiko pekerjaan:</p>
<ul>
  <li><strong>Pelatihan dasar</strong> untuk semua pekerja: pengenalan bahaya, APD, tanggap darurat, P3K dasar.</li>
  <li><strong>Pelatihan khusus bahaya</strong>: <?= ilink('bekerja-di-ketinggian', 'bekerja di ketinggian') ?>, <?= ilink('ruang-terbatas', 'ruang terbatas') ?>, K3 listrik, pemadaman kebakaran.</li>
  <li><strong>Pelatihan kompetensi bersertifikat</strong>: operator pesawat angkat, petugas P3K, regu pemadam, hingga pembinaan <?= ilink('ahli-k3-umum', 'Ahli K3 Umum') ?> melalui lembaga PJK3 yang ditunjuk Kemnaker.</li>
</ul>

