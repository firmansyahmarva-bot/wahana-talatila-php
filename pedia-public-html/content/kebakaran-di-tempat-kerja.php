<p><strong>Kebakaran di tempat kerja merenggut nyawa, aset, dan kelangsungan usaha sekaligus — dan hampir selalu berawal dari sumber penyalaan kecil yang dibiarkan bertemu bahan mudah terbakar.</strong> Kerangka pencegahannya diatur antara lain dalam Permenakertrans No. 4 Tahun 1980 (APAR) dan Kepmenaker No. 186 Tahun 1999 (unit penanggulangan kebakaran di tempat kerja).</p>

<h2 id="segitiga-api">Memahami Api: Segitiga Api dan Kelas Kebakaran</h2>
<p>Api membutuhkan <em>bahan bakar</em>, <em>oksigen</em>, dan <em>panas</em>. Pencegahan bekerja dengan menjauhkan ketiganya: mengelola penyimpanan bahan mudah terbakar, mengendalikan sumber panas (las, gerinda, instalasi <?= ilink('k3-listrik', 'listrik') ?>, merokok), dan menjaga housekeeping. Pemadaman memutus salah satu unsur — pendinginan, penyelimutan, atau pemisahan bahan bakar.</p>

<h2 id="pencegahan">Pencegahan</h2>
<ul>
  <li>Identifikasi area berisiko: gudang bahan kimia, area pengisian bahan bakar, dapur, ruang panel, area hot work.</li>
  <li>Izin kerja panas (hot work permit) untuk las/gerinda di luar bengkel — lengkap dengan fire watcher.</li>
  <li>Perawatan instalasi listrik dan larangan beban berlebih.</li>
  <li>Housekeeping: sampah mudah terbakar tidak menumpuk, jalur evakuasi tidak terhalang.</li>
</ul>

<h2 id="proteksi">Sarana Proteksi Kebakaran</h2>
<ul>
  <li><strong>Proteksi aktif</strong>: APAR sesuai kelas kebakaran (jarak antar-unit maksimal 15 m, mudah dijangkau, diperiksa berkala), hidran, sprinkler, serta detektor dan alarm kebakaran.</li>
  <li><strong>Proteksi pasif</strong>: kompartemenisasi, pintu tahan api, sarana jalan keluar yang cukup, dan penandaan jalur evakuasi.</li>
</ul>

<h2 id="organisasi">Organisasi Tanggap Darurat</h2>
<p>Kepmenaker 186/1999 mewajibkan unit penanggulangan kebakaran di tempat kerja sesuai tingkat risiko — dari petugas peran kebakaran per unit kerja hingga regu dan koordinator terlatih. Kelengkapannya: prosedur tanggap darurat, latihan evakuasi berkala (fire drill), titik kumpul, dan koordinasi dengan <?= ilink('permenaker-15-2008-p3k', 'fasilitas P3K') ?> untuk penanganan korban.</p>

