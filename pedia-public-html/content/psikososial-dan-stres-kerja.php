<p><strong>Faktor psikososial adalah aspek desain, organisasi, dan hubungan kerja yang berpotensi menimbulkan gangguan psikis maupun fisik — dan sejak Permenaker 5/2018, ia berstatus sama dengan bising atau debu: bahaya lingkungan kerja yang wajib dikelola.</strong></p>

<h2 id="sumber">Sumber Bahaya Psikososial</h2>
<ul>
  <li><strong>Isi pekerjaan</strong>: beban berlebih, tuntutan emosional tinggi, kerja monoton, tanggung jawab atas keselamatan orang lain.</li>
  <li><strong>Organisasi kerja</strong>: ketaksaan peran, konflik peran, kurang kendali atas cara dan ritme kerja, jam kerja panjang atau shift buruk — beririsan dengan <?= ilink('kelelahan-kerja-fatigue', 'fatigue') ?>.</li>
  <li><strong>Hubungan kerja</strong>: dukungan atasan/rekan yang rendah, komunikasi buruk, kekerasan, perundungan, dan pelecehan.</li>
  <li><strong>Konteks</strong>: ketidakamanan kerja, perubahan organisasi, ketimpangan penghargaan-usaha.</li>
</ul>

<h2 id="dampak">Dampak</h2>
<p>Pada individu: stres kronis, gangguan tidur, kecemasan, depresi, keluhan psikosomatik — beberapa dapat ditetapkan sebagai <?= ilink('penyakit-akibat-kerja', 'PAK') ?>. Pada keselamatan: pekerja yang tertekan lebih sering lalai, mengambil jalan pintas, dan enggan melaporkan bahaya. Pada organisasi: absensi, turnover, dan produktivitas — stres kerja adalah biaya besar yang jarang dihitung.</p>

<h2 id="penilaian">Penilaian Risiko Psikososial</h2>
<p>Perlakukan seperti bahaya lain: identifikasi (survei persepsi, data absensi/turnover, keluhan dari <?= ilink('pemeriksaan-kesehatan-tenaga-kerja', 'pemeriksaan kesehatan') ?>, wawancara kelompok), nilai tingkat risikonya per unit kerja, lalu kendalikan dan pantau ulang.</p>

<h2 id="pengendalian">Pengendalian</h2>
<ol>
  <li><strong>Di sumber (organisasi)</strong> — paling efektif: rancang ulang beban dan peran, jadwal manusiawi, kejelasan tugas, partisipasi pekerja dalam keputusan, kebijakan anti-kekerasan dan pelecehan yang ditegakkan.</li>
  <li><strong>Pada hubungan kerja</strong>: latih atasan mengenali tanda stres, saluran keluhan yang aman, dukungan sosial antar-rekan.</li>
  <li><strong>Pada individu</strong>: edukasi pengelolaan stres, akses konseling/bantuan profesional, dan program kesejahteraan — pelengkap, bukan pengganti pembenahan organisasi.</li>
</ol>
