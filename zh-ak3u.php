      <article class="zh-card">
        <span class="zh-sec-badge">机构设立实操</span>
        <h2 class="zh-sec-title">二、安全生产委员会 (P2K3) 的法定架构与运作规范</h2>
        <p class="zh-text">
          P2K3 全称为 <strong>Panitia Pembina Keselamatan dan Kesehatan Kerja</strong>，是印尼劳工部要求企业在内部设立的劳资双方法定安全监督组织。其组织架构具有严格的法规指定格式（依据 Permenaker No. 04/MEN/1987）：
        </p>
        <ul>
          <li><strong>P2K3 主席 (Ketua)：</strong> 必须由<strong>企业最高现场负责人（总经理 / 总厂长 / 现场项目总监）</strong>亲自担任，体现安全生产的第一责任人法定归属。</li>
          <li><strong>P2K3 秘书 (Sekretaris)：</strong> 必须由<strong>持有劳工部正式有效任职书的专职 Ahli K3 Umum</strong> 担任，负责具体安全制度编写、巡检监督与政府报备。</li>
          <li><strong>P2K3 委员 (Anggota)：</strong> 由中印双方生产车间主管、工程部长、HR 人事主管及工会代表共同组成。</li>
        </ul>
