        <h2 class="zh-sec-title">一、什么时候企业必须配备专职安全官 (Ahli K3 Umum)？</h2>
        <p class="zh-text">
          根据印尼 <strong>《1970年第1号安全生产法》第10条</strong> 及 <strong>劳工部第 02/MEN/1992 号条例</strong>，满足以下两项条件之一的企业，<strong>必须在组织架构中任命至少 1 名具备印尼劳工部正式任职许可（SKP: Surat Keputusan Penunjukan）的企业注册安全官（Ahli K3 Umum）</strong>：
        </p>
        <div class="zh-law-grid">
          <div class="zh-law-card">
            <strong>条件 A：用工人数达到 100 人及以上</strong>
            <p>无论从事何种行业（包括普通制造、组装、仓储、建筑或商贸物流），只要雇佣员工总数达到 100 人，企业即触达法定设立门槛。</p>
          </div>
          <div class="zh-law-card">
            <strong>条件 B：不足 100 人但属于高危行业</strong>
            <p>用工虽不足 100 人，但存在火灾易燃物、高压爆炸品、有毒危险化学品、电弧高压、重型机械或高空作业（如冶炼厂、化工厂、矿山、高压电网、爆破工程），同样属于强制设立范围。</p>
          </div>
        </div>
        <div class="zh-alert-box">
          <strong>未依法配置专职安全官的法律后果：</strong>
          <p>地方劳动监察局（Pengawas Ketenagakerjaan）在例行巡检或接到举报进厂核查时，第一项必查文件便是安全官的《劳工部委任书》（SKP）及《安全官执业证》（Kartu Kewenangan）。若未配置，监察局将签发限期整改通知书（Nota Pemeriksaan），逾期未整改企业将被处以行政罚款甚至暂扣生产许可。</p>
        </div>
