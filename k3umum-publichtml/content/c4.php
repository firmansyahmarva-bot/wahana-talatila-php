<h2 id="standar-sni">Standar SNI untuk APD</h2>
<p>Payung standarnya adalah <strong>SNI 19-1958-1990</strong> tentang Pedoman Alat Pelindung Diri, dilengkapi standar spesifik per jenis APD (misalnya SNI 8459:2017 untuk helm, SNI ISO 6161 untuk kacamata pelindung). Memilih APD ber-SNI bukan sekadar formalitas — spesifikasi ini menjamin APD benar-benar teruji menahan tingkat bahaya yang disasar.</p>

<h2 id="kewajiban-pengusaha">Kewajiban Pengusaha</h2>
<ol>
  <li>Menyediakan APD sesuai jenis bahaya di tempat kerja.</li>
  <li>Memastikan APD sesuai SNI atau standar yang berlaku.</li>
  <li>Memberikan APD secara cuma-cuma kepada pekerja.</li>
  <li>Melatih pekerja cara menggunakan APD dengan benar.</li>
</ol>

